def run_ttest(data, grouping_variable):

    temp = data[
        [
            grouping_variable,
            "consumer_trust"
        ]
    ].dropna()

    groups = temp[
        grouping_variable
    ].unique()

    print("\n" + "=" * 70)
    print(
        f"T-TEST: {grouping_variable}"
    )
    print("=" * 70)

    if len(groups) != 2:

        print(
            "This variable does not have exactly "
            "two groups."
        )

        print(
            "Number of groups:",
            len(groups)
        )

        return None

    group1 = temp.loc[
        temp[grouping_variable] == groups[0],
        "consumer_trust"
    ]

    group2 = temp.loc[
        temp[grouping_variable] == groups[1],
        "consumer_trust"
    ]

    # Welch t-test
    t_stat, p_value = ttest_ind(
        group1,
        group2,
        equal_var=False
    )

    # Levene test
    lev_stat, lev_p = levene(
        group1,
        group2
    )

    result = pd.DataFrame({

        "Group 1": [groups[0]],

        "Group 2": [groups[1]],

        "N Group 1": [len(group1)],

        "N Group 2": [len(group2)],

        "Mean Group 1": [group1.mean()],

        "Mean Group 2": [group2.mean()],

        "t-statistic": [t_stat],

        "p-value": [p_value],

        "Levene p-value": [lev_p]
    })

    display(
        result.round(4)
    )

    return result

