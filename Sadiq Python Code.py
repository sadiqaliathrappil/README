def run_anova(data, grouping_variable):

    temp = data[
        [
            grouping_variable,
            "consumer_trust"
        ]
    ].dropna()

    groups = []

    names = []

    for name, group in temp.groupby(
        grouping_variable
    ):

        values = group[
            "consumer_trust"
        ].values

        if len(values) >= 2:

            groups.append(values)
            names.append(name)

    print("\n" + "=" * 70)
    print(
        f"ANOVA: {grouping_variable}"
    )
    print("=" * 70)

    for name, values in zip(
        names,
        groups
    ):

        print(
            f"{name}: "
            f"N={len(values)}, "
            f"Mean={np.mean(values):.4f}, "
            f"SD={np.std(values, ddof=1):.4f}"
        )

    if len(groups) < 2:

        print(
            "Not enough groups for ANOVA."
        )

        return None

    f_stat, p_value = f_oneway(
        *groups
    )

    # Eta squared
    grand_mean = temp[
        "consumer_trust"
    ].mean()

    ss_between = sum(
        len(values)
        * (np.mean(values) - grand_mean) ** 2
        for values in groups
    )

    ss_total = sum(
        (
            temp["consumer_trust"]
            - grand_mean
        ) ** 2
    )

    eta_squared = (
        ss_between / ss_total
    )

    result = pd.DataFrame({

        "Demographic": [
            grouping_variable
        ],

        "F-statistic": [
            f_stat
        ],

        "p-value": [
            p_value
        ],

        "Eta-squared": [
            eta_squared
        ]
    })

    display(
        result.round(4)
    )

    return result

